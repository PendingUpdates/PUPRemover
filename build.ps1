<#
.SYNOPSIS
    Regenerates the self-contained PUPRemover-S1.ps1 and PUPRemover-Test.ps1
    from src/PUPCore.ps1 + the driver tails.

.DESCRIPTION
    PUPCore.ps1 is the single source of truth (PUP definitions + scan/remove/
    report engine). The two deliverables at the repo root are self-contained
    (core embedded) so they can be dropped onto an endpoint or into a
    SentinelOne script with no dependencies. Run this after editing anything
    under src/.
#>
[CmdletBinding()]
param()

$root = $PSScriptRoot
$core = Get-Content -LiteralPath (Join-Path $root 'src/PUPCore.ps1')    -Raw
$s1   = Get-Content -LiteralPath (Join-Path $root 'src/driver-s1.ps1')  -Raw
$test = Get-Content -LiteralPath (Join-Path $root 'src/driver-test.ps1') -Raw

$header = @"
# ###########################################################################
# AUTO-GENERATED by build.ps1 — do NOT edit this file directly.
# Source of truth: src/PUPCore.ps1 + src/driver-*.ps1. Edit those, re-run
# .\build.ps1, and commit the regenerated file.
# ###########################################################################

"@

$targets = @(
    @{ Out = 'PUPRemover-S1.ps1';   Driver = $s1 },
    @{ Out = 'PUPRemover-Test.ps1'; Driver = $test }
)
foreach ($t in $targets) {
    $outPath = Join-Path $root $t.Out
    $content = $header + $core + "`n" + $t.Driver
    Set-Content -LiteralPath $outPath -Value $content -Encoding UTF8
    Write-Host ("Built {0} ({1} lines)" -f $t.Out, (($content -split "`n").Count))
}
